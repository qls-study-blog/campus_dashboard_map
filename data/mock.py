def _trim_loops(coords):
    """裁剪高德驾车路线中因校园内部路禁行而产生的绕行岔路和环路。

    原理：正常公交轨迹一路向南（纬度单调递减）。
    1. 遇到"明显向北折返"（纬度增大 > 约20米）的冗余点直接剔除；
    2. 检测环路：如果当前点非常接近之前某个已保留的点（说明绕了一圈回来），
       去掉中间那段环路，直接接上。
    """
    if not coords:
        return coords
    trimmed = [coords[0]]
    for i in range(1, len(coords)):
        prev = trimmed[-1]
        cur = coords[i]
        # 纬度明显向北增大(>约20米) → 视为绕行冗余点，剔除
        if cur[0] > prev[0] + 0.0002:
            continue
        # 检测环路：当前点是否非常接近之前某个已保留的点（约50米内）
        loop_back = -1
        for j in range(len(trimmed) - 2, max(-1, len(trimmed) - 30), -1):
            if abs(cur[0] - trimmed[j][0]) < 0.0005 and abs(cur[1] - trimmed[j][1]) < 0.0005:
                loop_back = j
                break
        if loop_back >= 0:
            # 绕了一圈回到 loop_back 位置，去掉中间环路，从 loop_back 继续
            trimmed = trimmed[:loop_back + 1]
            continue
        trimmed.append(cur)
    return trimmed


def get_bus_route_from_amap():
    """调用高德驾车路径规划API，返回贴合真实道路的公交轨迹坐标（[[纬度,经度],...]）。
    途经点只取真实公交站点（终点站→三号→一号→二号→南大门），不加任何人工途经点，
    让高德自然走校内最东的最大弧线（110.3045）；再用 _trim_loops 剔除向北折返的冗余点。
    返回 None 表示请求失败，调用方应退回手工拐点数据。"""
    try:
        stops = get_bus_stops().dropna(subset=["站点"])
        if len(stops) < 2:
            return None
        origin = f"{stops.iloc[0]['经度']},{stops.iloc[0]['纬度']}"
        dest = f"{stops.iloc[-1]['经度']},{stops.iloc[-1]['纬度']}"
        # 途经点 = 真实公交站点 + 东缘南北路上的一个途经点
        # 让高德从最东顶点沿东缘那条实际道路继续向南，不向西折回
        wp_stops = [f"{row['经度']},{row['纬度']}" for _, row in stops.iloc[1:-1].iterrows()]
        waypoints = ";".join(wp_stops[:1] + ["110.304500,25.062200"] + wp_stops[1:])
        params = {
            "origin": origin,
            "destination": dest,
            "waypoints": waypoints,
            "extensions": "all",
            "key": AMAP_KEY,
        }
        resp = requests.get(
            "https://restapi.amap.com/v3/direction/driving",
            params=params,
            timeout=8,
        ).json()
        if resp.get("status") != "1":
            return None
        path = resp["route"]["paths"][0]
        coords = []
        for step in path["steps"]:
            polyline = step.get("polyline", "")
            for pt in polyline.split(";"):
                if not pt:
                    continue
                lng, lat = pt.split(",")
                coords.append([float(lat), float(lng)])
        if not coords:
            return None
        # 剔除向北折返冗余点
        coords = _trim_loops(coords)
        return coords if coords else None
    except Exception:
        return None


