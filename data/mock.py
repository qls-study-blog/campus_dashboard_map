def _smooth_curve(coords, samples_per_seg=8):
    """Catmull-Rom 样条平滑：在相邻拐点之间加密插值点，使折线转折顺滑。
    coords: [[纬度,经度],...]；返回加密后的 [[纬度,经度],...]。"""
    pts = np.array(coords, dtype=float)
    n = len(pts)
    if n < 3:
        return coords
    # 计算累积弦长作为参数 t，保证插值密度均匀
    diff = np.diff(pts, axis=0)
    dist = np.sqrt((diff[:, 0] ** 2) + (diff[:, 1] ** 2))
    t = np.concatenate(([0], np.cumsum(dist)))
    # 均匀化参数，避免折点处分布不均
    result = [pts[0]]
    # Catmull-Rom 分段插值（闭合处理边界点用端点重复）
    for i in range(n - 1):
        p0 = pts[max(i - 1, 0)]
        p1 = pts[i]
        p2 = pts[min(i + 1, n - 1)]
        p3 = pts[min(i + 2, n - 1)]
        for s in range(1, samples_per_seg):
            u = s / samples_per_seg
            u2, u3 = u * u, u * u * u
            # Catmull-Rom 基函数
            w0 = -0.5 * u3 + u2 - 0.5 * u
            w1 = 1.5 * u3 - 2.5 * u2 + 1.0
            w2 = -1.5 * u3 + 2.0 * u2 + 0.5 * u
            w3 = 0.5 * u3 - 0.5 * u2
            result.append(w0 * p0 + w1 * p1 + w2 * p2 + w3 * p3)
    result.append(pts[-1])
    return [[float(r[0]), float(r[1])] for r in result]


